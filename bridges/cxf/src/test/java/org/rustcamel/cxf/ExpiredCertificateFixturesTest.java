package org.rustcamel.cxf;

import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.cert.CertificateExpiredException;
import java.security.cert.CertificateNotYetValidException;
import java.security.cert.X509Certificate;
import java.security.interfaces.RSAPublicKey;
import java.util.Arrays;
import java.util.Base64;
import org.apache.wss4j.dom.WSConstants;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.w3c.dom.Document;
import org.w3c.dom.NodeList;

/** Fixture-level assertions for the expired-certificate test material generated by keytool. */
class ExpiredCertificateFixturesTest {

  private static final String RSA_SHA256 = "http://www.w3.org/2001/04/xmldsig-more#rsa-sha256";
  private static final String SHA256 = "http://www.w3.org/2001/04/xmlenc#sha256";

  @TempDir static Path tempDir;

  private static Path defaultStore;
  private static Path expiredStore;
  private static Path futureStore;
  private static Path sameDnStore;
  private static Path sha1Store;
  private static Path chainStore;
  private static Path truststore;

  @BeforeAll
  static void setUpFixtures() throws Exception {
    defaultStore = TestKeystoreHelper.createTestKeystore();
    expiredStore = TestKeystoreHelper.createExpiredTestKeystore();
    futureStore = TestKeystoreHelper.createFutureTestKeystore();
    sameDnStore = TestKeystoreHelper.createExpiredSameDnDifferentKeyKeystore();
    sha1Store = TestKeystoreHelper.createExpiredSha1TestKeystore();
    chainStore = TestKeystoreHelper.createExpiredChainKeystore(tempDir);
    truststore =
        TestKeystoreHelper.createTruststoreWithCertificate(
            expiredStore, TestKeystoreHelper.KEY_ALIAS);
  }

  @AfterAll
  static void tearDownFixtures() throws Exception {
    for (Path store :
        Arrays.asList(
            defaultStore,
            expiredStore,
            futureStore,
            sameDnStore,
            sha1Store,
            chainStore,
            truststore)) {
      if (store != null) {
        Files.deleteIfExists(store);
      }
    }
  }

  @Test
  void expiredFixture_isExpiredAndRsa2048() throws Exception {
    X509Certificate cert =
        TestKeystoreHelper.certificateFrom(expiredStore, TestKeystoreHelper.KEY_ALIAS);

    assertThrows(CertificateExpiredException.class, cert::checkValidity);
    assertEquals("RSA", cert.getPublicKey().getAlgorithm());
    assertEquals(2048, ((RSAPublicKey) cert.getPublicKey()).getModulus().bitLength());
  }

  @Test
  void futureFixture_isNotYetValid() throws Exception {
    X509Certificate cert =
        TestKeystoreHelper.certificateFrom(futureStore, TestKeystoreHelper.KEY_ALIAS);

    assertThrows(CertificateNotYetValidException.class, cert::checkValidity);
  }

  @Test
  void sameDnDifferentKeyFixture_hasSameSubjectAndDifferentDer() throws Exception {
    X509Certificate baseline =
        TestKeystoreHelper.certificateFrom(defaultStore, TestKeystoreHelper.KEY_ALIAS);
    X509Certificate sameDn =
        TestKeystoreHelper.certificateFrom(sameDnStore, TestKeystoreHelper.KEY_ALIAS);

    assertEquals(baseline.getSubjectX500Principal(), sameDn.getSubjectX500Principal());
    assertFalse(
        Arrays.equals(baseline.getEncoded(), sameDn.getEncoded()),
        "the same-DN fixture must carry a different key and certificate DER");
  }

  @Test
  void sha1Fixture_isSha1SignedAndExpired() throws Exception {
    X509Certificate cert =
        TestKeystoreHelper.certificateFrom(sha1Store, TestKeystoreHelper.KEY_ALIAS);

    assertTrue(cert.getSigAlgName().toUpperCase().contains("SHA1"), cert.getSigAlgName());
    assertThrows(CertificateExpiredException.class, cert::checkValidity);
  }

  @Test
  void chainFixture_hasTwoCertificatesAndExpiredLeaf() throws Exception {
    X509Certificate[] chain = TestKeystoreHelper.certificateChainFrom(chainStore, "leaf");

    assertEquals(2, chain.length, "the key entry chain must be leaf then CA");
    assertThrows(CertificateExpiredException.class, chain[0]::checkValidity);
    X509Certificate ca = TestKeystoreHelper.certificateFrom(chainStore, "ca");
    assertEquals(ca.getSubjectX500Principal(), chain[0].getIssuerX500Principal());
    assertEquals(ca.getSubjectX500Principal(), chain[1].getSubjectX500Principal());
  }

  @Test
  void truststoreFixture_containsPinnedCertificate() throws Exception {
    X509Certificate source =
        TestKeystoreHelper.certificateFrom(expiredStore, TestKeystoreHelper.KEY_ALIAS);

    KeyStore trust = KeyStore.getInstance("JKS");
    try (var in = Files.newInputStream(truststore)) {
      trust.load(in, TestKeystoreHelper.KEYSTORE_PASSWORD.toCharArray());
    }

    X509Certificate pinned = (X509Certificate) trust.getCertificate("pinned");
    assertArrayEquals(source.getEncoded(), pinned.getEncoded());
  }

  @Test
  void signedEnvelopeFactory_embedsExpiredCertificate() throws Exception {
    X509Certificate expired =
        TestKeystoreHelper.certificateFrom(expiredStore, TestKeystoreHelper.KEY_ALIAS);

    String signed =
        ExpiredSignedEnvelopeFactory.signSoap11(
            plainSoap11(),
            expiredStore,
            TestKeystoreHelper.KEY_ALIAS,
            RSA_SHA256,
            SHA256,
            false,
            false);

    Document doc = SoapEnvelopeHelper.parseResponse(signed);
    NodeList tokens = doc.getElementsByTagNameNS(WSConstants.WSSE_NS, "BinarySecurityToken");
    assertEquals(1, tokens.getLength(), "the signed envelope must carry one BinarySecurityToken");
    byte[] embedded = Base64.getMimeDecoder().decode(tokens.item(0).getTextContent().trim());

    assertArrayEquals(expired.getEncoded(), embedded);
  }

  private static String plainSoap11() {
    return """
        <soapenv:Envelope xmlns:soapenv="http://schemas.xmlsoap.org/soap/envelope/">
          <soapenv:Header/>
          <soapenv:Body><test:Hello xmlns:test="http://test.example.com">World</test:Hello></soapenv:Body>
        </soapenv:Envelope>
        """;
  }
}
