//! Native signer-descriptor boundary integration (Task 2.5).
//!
//! A nested module of the `cxf_test` integration target (declared with
//! `#[path]`), so the `--test cxf_test` filter keeps working.
//!
//! The negative case is end-to-end on the real native bridge: a genuinely
//! WSS-signed request whose certificate subject DN exceeds the Rust 4096-byte
//! bound is verified and exported by the Java side (Body-covering signature,
//! trusted certificate) and rejected by the Rust `validate_signer` bounds. The
//! route must not run and the response must be a non-WSS `Receiver` fault with
//! HTTP 500 — even under the profile's WSS-only `fault_status = 403` override.
//! The 500 (never 403, never 200) is what proves WSS actually verified and the
//! descriptor fault, not a verification failure, drove the response.

use std::sync::Arc;
use std::time::Duration;

use camel_api::Exchange;
use camel_component_cxf::config::CxfSecurityFields;
use camel_component_cxf::{CxfBridgePool, CxfComponent, CxfPoolConfig, CxfProfileConfig};
use camel_dsl::parse_yaml;
use camel_test::CamelTestContext;
use reqwest::StatusCode;

use crate::support::cxf::require_cxf_bridge_binary;
use crate::support::install_crypto_provider;
use crate::support::wait::wait_until;
use crate::{
    assert_soap12_fault_code, cxf_wsdl_path, http_client, init_tracing, post_soap,
    reserve_local_port,
};

/// The known signer descriptor of the checked-in WSS fixture certificate
/// (`tests/fixtures/cxf-wss-test-keystore.jks`, alias `alice`), in the exact
/// field forms the bridge exports (RFC 2253 DNs without spaces, lowercase-hex
/// serial, 64-lowercase-hex fingerprint). Produced by the fixture generator's
/// descriptor dump; asserted on the native positive metadata chain.
pub(crate) const ALICE_SUBJECT: &str = "CN=test-alice,O=RustCamel Test";
pub(crate) const ALICE_ISSUER: &str = "CN=test-alice,O=RustCamel Test";
pub(crate) const ALICE_SERIAL: &str = "a3806c093a3c0c3f";
pub(crate) const ALICE_FINGERPRINT: &str =
    "d4561910bc4f487820629b9d06bf8d667e856838989c21d44c4294dded160bac";

/// Asserts a native-consumer exchange carries the four dedicated signer
/// properties of the known fixture certificate and nothing auth-shaped.
pub(crate) fn assert_alice_signer_properties(exchange: &Exchange) {
    use camel_api::security_policy::principal_from_exchange;
    use camel_component_cxf::signer::{
        SIGNER_FINGERPRINT, SIGNER_ISSUER, SIGNER_SERIAL, SIGNER_SUBJECT,
    };

    for (key, expected) in [
        (SIGNER_SUBJECT, ALICE_SUBJECT),
        (SIGNER_ISSUER, ALICE_ISSUER),
        (SIGNER_SERIAL, ALICE_SERIAL),
        (SIGNER_FINGERPRINT, ALICE_FINGERPRINT),
    ] {
        assert_eq!(
            exchange.property(key).and_then(|v| v.as_str()),
            Some(expected),
            "signer property {key} must carry the known fixture value"
        );
    }
    assert!(
        principal_from_exchange(exchange).is_none(),
        "a signer descriptor must never assemble a Principal"
    );
    for key in exchange.properties.keys() {
        assert!(
            !key.starts_with("camel.auth."),
            "no camel.auth.* key may be written, got: {key}"
        );
    }
}

/// Long-subject-DN WSS fixture paths (generated by
/// `SignedRequestFixtureGeneratorTest.generateLongDnFixture`).
fn longdn_keystore_fixture() -> String {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/cxf-wss-longdn-keystore.jks")
        .to_string_lossy()
        .to_string()
}

fn longdn_signed_request_fixture() -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/cxf-wss-longdn-signed-request.xml")
}

/// One WSS consumer profile trusting the long-DN certificate, with the
/// WSS-only `fault_status = 403` override the descriptor fault must survive.
fn longdn_component(port: u16, wsdl_path: &str) -> CxfComponent {
    let store = longdn_keystore_fixture();
    let pool = Arc::new(
        CxfBridgePool::from_config(CxfPoolConfig {
            profiles: vec![CxfProfileConfig {
                name: "baddn".to_string(),
                address: None,
                wsdl_path: wsdl_path.to_string(),
                service_name: "{http://example.com/hello}HelloService".to_string(),
                port_name: "{http://example.com/hello}HelloPort".to_string(),
                security: CxfSecurityFields {
                    keystore_path: Some(store.clone()),
                    keystore_password: Some("changeit".to_string()),
                    truststore_path: Some(store),
                    truststore_password: Some("changeit".to_string()),
                    sig_username: Some("alice".to_string()),
                    fault_status: Some(403),
                    ..Default::default()
                },
            }],
            max_bridges: 4,
            bridge_start_timeout_ms: 30_000,
            health_check_interval_ms: 5_000,
            bridge_cache_dir: None,
            version: camel_component_cxf::BRIDGE_VERSION.to_string(),
            bind_address: Some(format!("http://127.0.0.1:{port}/cxf")),
            listener_tls: None,
            reconnect: Default::default(),
        })
        .unwrap(),
    );
    CxfComponent::new(pool)
}

/// Task 2.5 native assertion: a genuine WSS-signed request whose exported
/// signer descriptor fails the Rust bounds must produce a correlated
/// `soap:Server` (`Receiver`) fault with HTTP 500 — not the profile's
/// `fault_status = 403` (WSS faults only), not a route success — and the route
/// must not be dispatched.
#[tokio::test(flavor = "multi_thread")]
async fn cxf_consumer_invalid_signer_descriptor_is_receiver_500() {
    init_tracing();
    install_crypto_provider();
    let _binary = require_cxf_bridge_binary();
    let wsdl_path = cxf_wsdl_path();
    // allow-free-port: external JVM consumer, see reserve_local_port (bd rc-d70up)
    let port = reserve_local_port();

    let h = CamelTestContext::builder()
        .with_direct()
        .with_mock()
        .with_component(longdn_component(port, &wsdl_path))
        .build()
        .await;

    let yaml = format!(
        "routes:\n  - id: baddn-consumer\n    from: \"cxf://http://127.0.0.1:{port}/cxf/baddn?wsdl={wsdl_path}&service={{http://example.com/hello}}HelloService&port={{http://example.com/hello}}HelloPort&profile=baddn\"\n    steps:\n      - to: \"mock:signer-bad-hit\"\n      - set_body:\n          value:\n            constant: \"<hel:sayHelloResponse xmlns:hel='http://example.com/hello'><return>ok</return></hel:sayHelloResponse>\"\n"
    );
    for route in parse_yaml(&yaml).unwrap() {
        h.add_route(route).await.unwrap();
    }
    h.start().await;

    let base = format!("http://127.0.0.1:{port}/cxf/baddn");
    wait_until(
        "baddn consumer endpoint ready",
        Duration::from_secs(15),
        Duration::from_millis(200),
        || {
            let url = base.clone();
            async move {
                match http_client().get(&url).send().await {
                    Ok(_) => Ok(true),
                    Err(_) => Ok(false),
                }
            }
        },
    )
    .await
    .unwrap();

    let signed = std::fs::read_to_string(longdn_signed_request_fixture())
        .expect("long-DN signed request fixture must be readable");
    assert!(
        signed.contains("Signature") && signed.contains("Security"),
        "the long-DN fixture must carry a real WS-Security signature"
    );

    let res = post_soap(&base, "application/soap+xml", "sayHello", signed).await;
    assert_eq!(
        res.status(),
        StatusCode::INTERNAL_SERVER_ERROR,
        "a descriptor failure is a Receiver fault: HTTP 500 even under the 403 \
         override (403 would mean WSS itself failed)"
    );
    let body = res.text().await.unwrap();
    assert_soap12_fault_code(&body, "Receiver");
    assert!(
        body.contains("subject"),
        "the fault must name the offending descriptor field (Rust bounds \
         rejection), got: {body}"
    );

    let hit = h.mock().get_endpoint("signer-bad-hit").unwrap();
    assert!(
        hit.get_received_exchanges().await.is_empty(),
        "the route must not be dispatched for an invalid descriptor"
    );

    h.stop().await;
}
